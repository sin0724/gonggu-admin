/** 현재 경로에 맞는 화면 가이드 키 */
export function guideKeyForPath(pathname: string): string {
  if (pathname === "/") return "dashboard";
  if (pathname === "/campaigns") return "campaigns-list";
  if (pathname.startsWith("/campaigns/active")) return "campaigns-active";
  if (pathname.startsWith("/campaigns/pipeline")) return "campaigns-pipeline";
  if (pathname.startsWith("/campaigns/new")) return "campaigns-new";
  if (/^\/campaigns\/[^/]+\/edit/.test(pathname)) return "campaigns-edit";
  if (/^\/campaigns\/[^/]+/.test(pathname)) return "campaign-detail";
  const first = pathname.split("/")[1];
  return PAGE_GUIDES.some((g) => g.key === first) ? first : "dashboard";
}

export function guideForPath(pathname: string): PageGuide {
  const key = guideKeyForPath(pathname);
  return PAGE_GUIDES.find((g) => g.key === key) ?? PAGE_GUIDES[0];
}

